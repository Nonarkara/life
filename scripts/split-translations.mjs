// Split dist/course/translations.js into per-language packs for lazy loading.
// Reads the full phrases array (English + Thai + zh-CN + ja + ko columns)
// and writes one JS module per language exporting a Map: English -> translated.
//
// Usage: node scripts/split-translations.mjs
//
// Output files (in dist/course/):
//   translations-en.js   (English: identity map, used as fallback)
//   translations-th.js   (Thai)
//   translations-zh-CN.js (Simplified Chinese)
//   translations-ja.js   (Japanese)
//   translations-ko.js   (Korean)
//
// i18n.js imports only the pack for the selected language (not English, which
// uses source phrases directly).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve('.');
const TRANSLATIONS = join(ROOT, 'dist', 'course', 'translations.js');
const OUT = join(ROOT, 'dist', 'course');

const ORDER = ['th', 'zh-CN', 'ja', 'ko']; // columns after English
const LANG_NAMES = { th: 'ไทย', 'zh-CN': '简体中文', ja: '日本語', ko: '한국어' };

// Evaluate translations.js to get the full phrases array.
const modUrl = 'file://' + TRANSLATIONS;
const mod = await import(modUrl);
const phrases = mod.phrases;

if (!Array.isArray(phrases)) {
  console.error('translations.js does not export a phrases array');
  process.exit(1);
}

// Build per-language maps: English phrase -> translated string.
const maps = {};
for (const lang of ORDER) maps[lang] = new Map();
let duplicateKeys = 0;

for (const row of phrases) {
  if (!Array.isArray(row) || row.length < 2) continue;
  const english = row[0];
  if (!english) continue;
  if (maps[ORDER[0]].has(english)) duplicateKeys++;
  for (let i = 0; i < ORDER.length; i++) {
    const lang = ORDER[i];
    const translation = row[i + 1];
    if (translation && translation !== english) {
      maps[lang].set(english, translation);
    }
  }
}

// Write each per-language pack as a JS module exporting a Map.
function writePack(lang, map) {
  const entries = [...map.entries()];
  const lines = ['// Auto-generated by scripts/split-translations.mjs — do not edit by hand.',
    `// Per-language translation pack for ${LANG_NAMES[lang]} (${lang}).`,
    '// English source phrase -> translated phrase.',
    'export default new Map([',
  ];
  for (const [key, value] of entries) {
    const k = JSON.stringify(key);
    const v = JSON.stringify(value);
    lines.push(`  [${k}, ${v}],`);
  }
  lines.push(']);');
  writeFileSync(join(OUT, `translations-${lang}.js`), lines.join('\n') + '\n');
  console.log(`  translations-${lang}.js: ${entries.length} entries`);
}

for (const lang of ORDER) {
  writePack(lang, maps[lang]);
}

// Also write an English pack (identity: source phrase -> itself) for symmetry.
// English uses source phrases directly, but having the pack makes the loader uniform.
const enEntries = [...new Set(phrases.map(r => r[0]).filter(Boolean))];
const enLines = ['// Auto-generated by scripts/split-translations.mjs — do not edit by hand.',
  '// English translation pack: identity map (source phrase -> itself).',
  'export default new Map([',
];
for (const key of enEntries) {
  enLines.push(`  [${JSON.stringify(key)}, ${JSON.stringify(key)}],`);
}
enLines.push(']);');
writeFileSync(join(OUT, 'translations-en.js'), enLines.join('\n') + '\n');
console.log(`  translations-en.js: ${enEntries.length} entries (identity)`);

console.log(`\nSplit complete: ${phrases.length} total phrases, ${duplicateKeys} duplicate English keys.`);
console.log('Next: update dist/course/i18n.js to import only the selected language pack.');
